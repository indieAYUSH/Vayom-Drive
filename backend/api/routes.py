@router.get("/albums/{album_id}/download-zip")
async def download_album_zip(album_id: str, request: Request):
    """
    Builds all files inside an album/folder into a compressed .zip archive.

    The archive is written to a temporary file and streamed afterwards, so a
    large album never buffers every file (or the whole ZIP) in memory. Vault
    and completeness checks run before the response starts: a locked vault
    returns 423 and an interrupted upload returns 409 instead of emitting a
    truncated 200 response whose entries are ciphertext.
    """
    import zipfile
    from ..streaming.router import RangeSpec

    async with get_db() as db:
        cur_a = await db.execute("SELECT name FROM albums WHERE id = ?", (album_id,))
        alb_row = await cur_a.fetchone()
        if not alb_row:
            raise HTTPException(status_code=404, detail="Album not found")
        album_name = alb_row[0] or f"album_{album_id}"

        cur_f = await db.execute(
            """
            SELECT f.id, f.filename, f.size_bytes, f.encryption, f.nonce,
                   f.storage_backend, f.upload_status, f.total_parts
            FROM files f
            JOIN file_albums fa ON f.id = fa.file_id
            WHERE fa.album_id = ? AND f.is_deleted = 0 AND f.kind = 'original'
            ORDER BY f.filename ASC
            """,
            (album_id,)
        )
        file_rows = [dict(r) for r in await cur_f.fetchall()]

    if not file_rows:
        raise HTTPException(status_code=404, detail="No files found in this album")

    key_hex = request.headers.get("x-decryption-key") or request.query_params.get("key")
    key = bytes.fromhex(key_hex.strip()) if key_hex and len(key_hex.strip()) == 64 else None
    if key is None:
        from ..crypto import vault_manager
        key = vault_manager.get_key()

    # Preload and validate every file BEFORE committing to a 200 response.
    prepared: List[tuple] = []
    for f_item in file_rows:
        async with get_db() as db:
            p_cur = await db.execute(
                "SELECT * FROM file_parts WHERE file_id = ? ORDER BY part_index ASC",
                (f_item["id"],)
            )
            parts = [dict(p) for p in await p_cur.fetchall()]

        if f_item.get("encryption") == "ctr" and key is None:
            raise HTTPException(
                status_code=423,
                detail=(
                    f"Vault is locked. A decryption key is required to export "
                    f"'{f_item['filename']}'."
                ),
            )
        if is_upload_incomplete(f_item, parts):
            raise HTTPException(
                status_code=409,
                detail=(
                    f"'{f_item['filename']}' is still uploading or was interrupted. "
                    "Resume the upload before downloading the album."
                ),
            )
        part_sizes = [p.get("part_size_bytes") for p in parts]
        if parts and all(s is not None for s in part_sizes) and sum(part_sizes) != f_item["size_bytes"]:
            raise HTTPException(
                status_code=409,
                detail=(
                    f"'{f_item['filename']}' has an incomplete part set. "
                    "Resume the upload before downloading the album."
                ),
            )
        prepared.append((f_item, parts))

    safe_album_name = re.sub(r'[^a-zA-Z0-9_\-\. ]', '_', album_name).strip() or "folder"

    # TemporaryFile() spills to disk, so memory stays O(chunk) regardless of
    # album size. It is unlinked automatically when closed.
    archive = tempfile.TemporaryFile()
    try:
        with zipfile.ZipFile(archive, "w", zipfile.ZIP_DEFLATED) as zf:
            used_names: set = set()
            for f_item, parts in prepared:
                tot_sz = f_item["size_bytes"]
                spec = RangeSpec(
                    start=0,
                    end=tot_sz - 1,
                    total_size=tot_sz,
                    content_length=tot_sz,
                    is_range=False,
                    is_satisfiable=True,
                    is_capped=False
                )
                # H-09: entries must be flat relative names — raw client
                # filenames could carry path separators (Zip Slip on extract)
                base = Path(f_item["filename"]).name or f"{f_item['id']}.bin"
                base = base.replace("\\", "_").strip() or f"{f_item['id']}.bin"
                entry_name = base
                dedupe = 1
                while entry_name in used_names:
                    stem, dot, ext = base.rpartition(".")
                    entry_name = f"{stem}_{dedupe}.{ext}" if stem else f"{base}_{dedupe}"
                    dedupe += 1
                used_names.add(entry_name)
                with zf.open(entry_name, "w") as dest:
                    async for chunk in streaming_engine.stream_range(
                        parts=parts,
                        total_size=tot_sz,
                        range_spec=spec,
                        storage_client=storage_client,
                        encryption=f_item.get("encryption", "none"),
                        nonce=f_item.get("nonce"),
                        key=key
                    ):
                        dest.write(chunk)
        archive.seek(0)
    except Exception:
        archive.close()
        raise

    def iter_archive():
        try:
            while data := archive.read(256 * 1024):
                yield data
        finally:
            archive.close()

    headers = {
        "Content-Disposition": f'attachment; filename="{safe_album_name}.zip"',
        "Content-Type": "application/zip",
    }
    return StreamingResponse(iter_archive(), headers=headers, media_type="application/zip")


