async def _without_parts_shared_with_surviving_files(parts: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
    """B2: cloned proxy parts reference remote objects that surviving files
    still use; drop those from a purge set so deleting one duplicate doesn't
    destroy the other's data."""
    if not parts:
        return parts
    purged = list({p["file_id"] for p in parts if p.get("file_id")})
    if not purged:
        return parts
    ph = ",".join("?" * len(purged))
    kept: List[Dict[str, Any]] = []
    async with get_db() as db:
        for p in parts:
            if p.get("telegram_message_id") is not None:
                cur = await db.execute(
                    f"SELECT 1 FROM file_parts WHERE telegram_message_id = ? "
                    f"AND IFNULL(telegram_channel_id, '') = IFNULL(?, '') "
                    f"AND file_id NOT IN ({ph}) LIMIT 1",
                    (p["telegram_message_id"], p.get("telegram_channel_id"), *purged),
                )
                if await cur.fetchone() is not None:
                    continue
            elif p.get("storage_uri"):
                cur = await db.execute(
                    f"SELECT 1 FROM file_parts WHERE storage_uri = ? AND file_id NOT IN ({ph}) LIMIT 1",
                    (p["storage_uri"], *purged),
                )
                if await cur.fetchone() is not None:
                    continue
            kept.append(p)
    return kept


async def purge_parts_from_storage(parts: List[Dict[str, Any]]) -> int:
    """Purges parts from their respective underlying storage backends.

    Returns the number of parts actually purged; remote objects still
    referenced by surviving files are kept (B2)."""
    if not parts:
        return 0
    parts = await _without_parts_shared_with_surviving_files(parts)
    if not parts:
        return 0
    from ..storage.manager import get_storage_adapter
    tg_parts = [p for p in parts if (p.get("storage_backend") or "telegram") == "telegram"]
    if tg_parts:
        await storage_client.delete_parts(tg_parts)

    other_backends = {p.get("storage_backend") for p in parts if p.get("storage_backend") and p.get("storage_backend") != "telegram"}
    for b in other_backends:
        b_parts = [p for p in parts if p.get("storage_backend") == b]
        adapter = get_storage_adapter(b)
        await adapter.delete_parts(b_parts)
    return len(parts)


