@router.get("/s/{token}")
async def access_shared_file(
    token: str,
    request: Request,
    range_header: Optional[str] = Header(None, alias="Range"),
    password: Optional[str] = Query(None),
    x_share_password: Optional[str] = Header(None, alias="X-Share-Password")
):
    """Public streaming download endpoint for a valid share link."""
    _require_share_links_enabled()
    async with get_db() as db:
        cursor = await db.execute(
            """
            SELECT s.*, f.filename, f.mime_type, f.size_bytes
            FROM share_links s
            JOIN files f ON s.file_id = f.id
            WHERE s.token = ? AND s.is_revoked = 0 AND f.is_deleted = 0
            """,
            (token,)
        )
        share = await cursor.fetchone()
        if not share:
            raise HTTPException(status_code=404, detail="Shared link not found or revoked")

        s_dict = dict(share)

        # Expiry enforcement (stored as UTC text by create_share_link).
        expires_raw = s_dict.get("expires_at")
        if expires_raw:
            if isinstance(expires_raw, datetime):
                expires_dt = (
                    expires_raw if expires_raw.tzinfo
                    else expires_raw.replace(tzinfo=timezone.utc)
                )
            else:
                expires_dt = None
                for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%d %H:%M:%S.%f"):
                    try:
                        expires_dt = datetime.strptime(str(expires_raw), fmt).replace(tzinfo=timezone.utc)
                        break
                    except ValueError:
                        continue
            if expires_dt is None or datetime.now(timezone.utc) >= expires_dt:
                raise HTTPException(status_code=410, detail="Share link has expired")

        # Password enforcement. Legacy plaintext rows are accepted once and upgraded.
        stored_password = s_dict.get("password_hash")
        if stored_password:
            supplied_password = password if password is not None else (x_share_password or "")
            if not verify_share_password(supplied_password, stored_password):
                raise HTTPException(
                    status_code=401,
                    detail="Share password required or incorrect",
                    headers={"WWW-Authenticate": 'SharePassword realm="Vayom Drive"'}
                )
            if not stored_password.startswith("pbkdf2_sha256$"):
                await db.execute(
                    "UPDATE share_links SET password_hash = ? WHERE id = ?",
                    (hash_share_password(supplied_password), s_dict["id"])
                )

        if s_dict.get("max_views") and s_dict["view_count"] >= s_dict["max_views"]:
            raise HTTPException(status_code=410, detail="Share link view limit exceeded")

        # Count a view only for the initial request. Range seeks and HEAD probes
        # must not consume the share's remaining views.
        is_initial_view = (
            request.method != "HEAD"
            and (not range_header or range_header.strip().lower().startswith("bytes=0-"))
        )
        if is_initial_view:
            cur = await db.execute(
                """
                UPDATE share_links SET view_count = view_count + 1
                WHERE id = ? AND (max_views IS NULL OR max_views = 0 OR view_count < max_views)
                """,
                (s_dict["id"],)
            )
            if cur.rowcount == 0:
                raise HTTPException(status_code=410, detail="Share link view limit exceeded")
        await db.commit()

    return await download_file(file_id=s_dict["file_id"], request=request, range_header=range_header)


