@router.post("/files/{file_id}/generate-proxy")
async def trigger_proxy_generation(
    file_id: str,
    force_download: bool = Query(False),
    force: bool = Query(False),
    source_path: Optional[str] = Query(None)
):
    """
    Triggers compact 480p proxy generation for a video.

    Reuses a local source when available. If the video only exists remotely,
    force_download=True authorizes downloading it (or its older large proxy)
    once and re-encoding it in the background.
    """
    old_proxy_id: Optional[str] = None
    async with get_db() as db:
        cur = await db.execute("SELECT * FROM files WHERE id = ?", (file_id,))
        row = await cur.fetchone()
        if not row:
            raise HTTPException(status_code=404, detail="File not found")
        f_dict = dict(row)

        if f_dict.get("file_category") != "video":
            raise HTTPException(status_code=400, detail="File is not a video")

        p_cur = await db.execute(
            """
            SELECT id, proxy_profile, height, upload_status
            FROM files
            WHERE proxy_of = ? AND kind = 'proxy' AND is_deleted = 0
            ORDER BY created_at DESC
            """,
            (file_id,),
        )
        proxies = [dict(r) for r in await p_cur.fetchall()]
        current = next(
            (
                p for p in proxies
                if p.get("proxy_profile") == PROXY_PROFILE
                and p.get("upload_status") == "completed"
                and (not p.get("height") or int(p["height"]) <= PROXY_MAX_HEIGHT)
            ),
            None,
        )
        if current and not force:
            return {
                "status": "ready",
                "profile": PROXY_PROFILE,
                "message": "480p proxy already generated and ready.",
            }

        if f_dict.get("proxy_status") in ("queued", "encoding", "uploading"):
            return {"status": "in_progress", "profile": PROXY_PROFILE}

        # Prefer an older proxy as the download source: it is already a small
        # H.264 file, so the upgrade downloads less than the original.
        old_proxy_id = next(
            (p["id"] for p in proxies if p.get("upload_status") == "completed"),
            None,
        )

    # Search for local source in parameters, watch folders, or local folders
    local_source: Optional[Path] = None
    if source_path:
        # H-04: never let the caller point ffmpeg at an arbitrary local file.
        # Explicit paths must stay inside the allowlisted workstation roots.
        from ..workstation.security import is_safe_file_path
        candidate = Path(source_path).expanduser()
        if not is_safe_file_path(candidate):
            raise HTTPException(
                status_code=400,
                detail="source_path is outside the allowlisted workstation roots."
            )
        if candidate.exists() and candidate.is_file():
            local_source = candidate
    else:
        async with get_db() as db:
            w_cur = await db.execute("SELECT file_path FROM watch_folder_events WHERE file_id = ? ORDER BY id DESC LIMIT 1", (file_id,))
            w_row = await w_cur.fetchone()
            if w_row and Path(w_row[0]).exists():
                local_source = Path(w_row[0])
            else:
                candidates = [
                    Path.home() / "Desktop" / "gameplay" / f_dict["filename"],
                    Path.home() / "Desktop" / f_dict["filename"],
                    Path.home() / "Downloads" / f_dict["filename"],
                    settings.DATA_DIR / "uploads" / file_id / f_dict["filename"]
                ]
                for cand in candidates:
                    if cand.exists():
                        local_source = cand
                        break

    if not local_source and not force_download:
        raise HTTPException(
            status_code=400,
            detail="Local source video not found on disk. Explicit confirmation (force_download=True) required before downloading remote file."
        )

    if local_source:
        await transcoding_manager.enqueue_proxy(file_id, local_source)
        return {
            "status": "queued",
            "profile": PROXY_PROFILE,
            "message": f"480p proxy enqueued from local source ({local_source.name}).",
        }

    await transcoding_manager.enqueue_remote_proxy(file_id, old_proxy_id)
    source_note = "existing compressed proxy" if old_proxy_id else "original from Telegram"
    return {
        "status": "queued",
        "profile": PROXY_PROFILE,
        "message": f"480p proxy queued from {source_note}.",
    }


@router.api_route("/files/{file_id}/thumbnail", methods=["GET", "HEAD"])
async def get_thumbnail(file_id: str):
    """Serves the ultra-compact WebP thumbnail preview with on-demand fallback."""
    async with get_db() as db:
        cursor = await db.execute("SELECT id, is_deleted, has_thumbnail, file_category, filename, size_bytes FROM files WHERE id = ?", (file_id,))
        file_row = await cursor.fetchone()
        if not file_row or file_row["is_deleted"]:
            raise HTTPException(status_code=404, detail="Thumbnail not found")

        file_item = dict(file_row)

    thumb = settings.THUMBNAIL_DIR / f"{file_id}.webp"
    if thumb.exists():
        return FileResponse(thumb, media_type="image/webp")

    # On-demand generation: if file exists in DB but thumbnail was not generated or lost
    category = file_item["file_category"]
    has_thumb = False
    try:
        if category == "video":
            token_param = f"?token={settings.STREAM_LOOPBACK_TOKEN}" if settings.STREAM_LOOPBACK_TOKEN else ""
            stream_url = f"http://127.0.0.1:{settings.PORT}/api/v1/virtual-stream/{file_id}{token_param}"
            has_thumb = await generate_video_thumbnail(stream_url, thumb)
        elif category == "image":
            # Fetch image bytes and generate thumbnail
            async with get_db() as db:
                p_cur = await db.execute(
                    "SELECT telegram_message_id, telegram_channel_id FROM file_parts WHERE file_id = ? ORDER BY part_index ASC LIMIT 1",
                    (file_id,)
                )
                p_row = await p_cur.fetchone()
            if p_row:
                tmp_img = settings.DATA_DIR / f"tmp_thumb_{file_id}"
                # Download the complete image.  The old 2 MiB cap truncated larger
                # PNGs, so Pillow rejected every thumbnail of a valid photo.
                image_size = file_item.get("size_bytes") or None
                try:
                    with open(tmp_img, "wb") as f:
                        async for chunk in storage_client.stream_part_bytes(
                            p_row[0], channel_id=p_row[1], offset=0, limit=image_size
                        ):
                            f.write(chunk)
                    has_thumb = generate_webp_thumbnail(tmp_img, thumb)
                finally:
                    try:
                        tmp_img.unlink()
                    except Exception:
                        pass

        if has_thumb and thumb.exists():
            async with get_db() as db:
                await db.execute("UPDATE files SET has_thumbnail = 1, thumbnail_path = ? WHERE id = ?", (str(thumb), file_id))
                await db.commit()
            return FileResponse(thumb, media_type="image/webp")
    except Exception as e:
        logger.warning(f"On-demand thumbnail generation failed for {file_id}: {e}")

    raise HTTPException(status_code=404, detail="Thumbnail not found")


@router.api_route("/files/{file_id}/download", methods=["GET", "HEAD"])
async def download_file(
    file_id: str,
    request: Request,
    range_header: Optional[str] = Header(None, alias="Range"),
    inline: bool = Query(False)
):
    """
    Streams file bytes with full HTTP Range request support (206 Partial Content).
    Supports both attachment download and inline streaming/viewing.
    """
    async with get_db() as db:
        cursor = await db.execute("SELECT * FROM files WHERE id = ? AND is_deleted = 0", (file_id,))
        file_row = await cursor.fetchone()
        if not file_row:
            raise HTTPException(status_code=404, detail="File not found")

        file_item = dict(file_row)
        p_cursor = await db.execute(
            "SELECT * FROM file_parts WHERE file_id = ? ORDER BY part_index ASC",
            (file_id,)
        )
        parts = [dict(p) for p in await p_cursor.fetchall()]
        if not parts:
            raise HTTPException(status_code=404, detail="File content parts not found")

        if is_upload_incomplete(file_item, parts):
            raise HTTPException(
                status_code=409,
                detail="File upload was interrupted. Resume the upload before downloading."
            )

    total_size = file_item["size_bytes"]
    filename = file_item["filename"]

    # Infer or correct media_type (critical for inline PDF and document preview)
    media_type = file_item.get("mime_type")
    if not media_type or media_type == "application/octet-stream":
        guessed, _ = mimetypes.guess_type(filename)
        media_type = guessed or ("application/pdf" if filename.lower().endswith(".pdf") else "application/octet-stream")

    # Determine disposition: inline if requested via param, if path is /view, or if inline query is set
    is_inline = (
        inline
        or request.url.path.endswith("/view")
        or request.query_params.get("inline", "").lower() in ("true", "1", "yes")
    )
    disposition_type = "inline" if is_inline else "attachment"

    # Parse range for downloads: do not cap range so downloads & resume stream continuously
    range_spec = parse_and_clamp_range(range_header, total_size, max_chunk_bytes=None)

    if not range_spec.is_satisfiable:
        headers = {
            "Content-Range": range_spec.content_range_header,
            "Accept-Ranges": "bytes"
        }
        return Response(status_code=status.HTTP_416_RANGE_NOT_SATISFIABLE, headers=headers)

    headers = {
        "Accept-Ranges": "bytes",
        "Content-Length": str(range_spec.content_length),
        "Content-Disposition": format_content_disposition(filename, disposition_type=disposition_type)
    }
    if range_spec.is_range:
        headers["Content-Range"] = range_spec.content_range_header
        status_code = status.HTTP_206_PARTIAL_CONTENT
    else:
        status_code = status.HTTP_200_OK

    if request.method == "HEAD":
        return Response(status_code=status_code, headers=headers, media_type=media_type)

    encryption = file_item.get("encryption", "none")
    nonce = file_item.get("nonce")
    key_hex = request.headers.get("x-decryption-key") or request.query_params.get("key")
    key = None
    if key_hex:
        clean_key = key_hex.strip()
        if len(clean_key) == 64:
            try:
                key = bytes.fromhex(clean_key)
            except ValueError:
                pass
    if key is None:
        from ..crypto import vault_manager
        key = vault_manager.get_key()

    if encryption == "ctr" and key is None:
        raise HTTPException(
            status_code=423,
            detail="Vault is locked. Decryption key or passphrase required to decrypt this file."
        )

    return StreamingResponse(
        streaming_engine.stream_range(
            parts=parts,
            total_size=total_size,
            range_spec=range_spec,
            storage_client=storage_client,
            encryption=encryption,
            nonce=nonce,
            key=key
        ),
        status_code=status_code,
        headers=headers,
        media_type=media_type
    )


