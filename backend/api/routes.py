# In-memory real-time upload progress tracking keyed by task_id
upload_progress_tracker: Dict[str, Dict[str, Any]] = {}

async def expire_tracker_entry(task_id: str, owner_file_id: "str | None", delay: float = 60.0) -> None:
    # Retries reuse the same task_id, so a TTL pop must only remove the entry
    # created by the attempt that scheduled it (owner_file_id); otherwise it
    # evicts a live retried upload mid-flight (B1).
    await asyncio.sleep(delay)
    entry = upload_progress_tracker.get(task_id)
    if entry is not None and entry.get("file_id") == owner_file_id:
        upload_progress_tracker.pop(task_id, None)

def generate_file_id() -> str:
    """Generates continuous alphanumeric ID without hyphens to prevent Telegram search word-breaking."""
    return f"v_{uuid.uuid4().hex}"

def generate_part_id() -> str:
    """Generates continuous alphanumeric part ID."""
    return f"vp_{uuid.uuid4().hex}"

# File IDs are always generated by generate_file_id(); rejecting anything else
# prevents path traversal through the upload staging directory.
_FILE_ID_RE = re.compile(r"^v_[0-9a-f]{32}$")
_NONCE_RE = re.compile(r"^[0-9a-f]{16}$")


def validate_file_id(file_id: str) -> str:
    """Returns a normalized file ID or raises 400 for malformed/unsafe IDs."""
    clean_id = (file_id or "").strip()
    if not _FILE_ID_RE.fullmatch(clean_id):
        raise HTTPException(status_code=400, detail="Invalid file ID format")
    return clean_id


def normalize_nonce(nonce: Optional[str]) -> Optional[str]:
    """Validates a CTR nonce (8 bytes / 16 hex chars) and normalizes its case."""
    if nonce is None:
        return None
    clean_nonce = nonce.strip().lower()
    if not clean_nonce:
        return None
    if not _NONCE_RE.fullmatch(clean_nonce):
        raise HTTPException(status_code=400, detail="Invalid nonce: expected 16 hexadecimal characters")
    return clean_nonce


_SHARE_PASSWORD_ITERATIONS = 260_000


def is_upload_incomplete(file_item: Dict[str, Any], parts: List[Dict[str, Any]]) -> bool:
    """
    C-4: decides whether a file's stored parts are a complete representation.

    `files.upload_status` is only ever 'uploading' or 'completed' on the
    chunked-upload path, so the legacy 'interrupted' literal alone is not a
    reliable signal: a file whose part set is short would be streamed as if it
    were whole, advertising the full Content-Length and then aborting mid-body.

    This mirrors the condition the file-list endpoint already exposes as
    `is_interrupted`, so the gallery and the streaming endpoints always agree.
    """
    if file_item.get("upload_status") == "interrupted":
        return True
    total_parts = file_item.get("total_parts") or 1
    if file_item.get("upload_status") == "completed":
        return False
    return len(parts) < total_parts


def hash_share_password(password: str) -> str:
    """Hashes a share-link password with PBKDF2-HMAC-SHA256 and a random salt."""
    salt = os.urandom(16)
    derived = hashlib.pbkdf2_hmac(
        "sha256", password.encode("utf-8"), salt, _SHARE_PASSWORD_ITERATIONS
    )
    return f"pbkdf2_sha256${_SHARE_PASSWORD_ITERATIONS}${salt.hex()}${derived.hex()}"


def verify_share_password(password: str, stored: str) -> bool:
    """Constant-time verification of a share password; supports legacy plaintext rows."""
    if not stored:
        return True
    if stored.startswith("pbkdf2_sha256$"):
        try:
            _, iterations, salt_hex, expected_hex = stored.split("$", 3)
            derived = hashlib.pbkdf2_hmac(
                "sha256",
                (password or "").encode("utf-8"),
                bytes.fromhex(salt_hex),
                int(iterations),
            )
            return hmac.compare_digest(derived.hex(), expected_hex)
        except (ValueError, TypeError):
            return False
    return hmac.compare_digest((password or "").encode("utf-8"), stored.encode("utf-8"))


def is_offline_mock_upload(result: Any) -> bool:
    """True when storage_client returned a local mock blob instead of a real upload."""
    return isinstance(result, dict) and bool(result.get("mock"))


def reject_offline_mock_upload(result: Any) -> None:
    """
    Fail closed when Telegram is disconnected and the storage client only wrote
    a local mock blob. In production those bytes are not recoverable after the
    local copy is deleted, so they must never be recorded as a completed upload.
    Unit tests/offline demos may opt in with ALLOW_OFFLINE_MOCK_UPLOADS=true.
    """
    if is_offline_mock_upload(result) and not getattr(
        settings, "ALLOW_OFFLINE_MOCK_UPLOADS", False
    ):
        raise HTTPException(
            status_code=503,
            detail=(
                "Storage backend is offline. The upload was not saved; "
                "reconnect to Telegram and retry."
            ),
        )


def encrypt_file_ctr_to_path(
    source: Path,
    destination: Path,
    key: bytes,
    nonce_hex: str,
) -> str:
    """
    Streams a whole file through AES-256-CTR into a temporary ciphertext file.
    Returns the ciphertext SHA-256. Used for non-Telegram adapters, which take
    a filesystem path rather than the zero-copy EncryptedFileSlice wrapper.
    """
    from ..crypto import EncryptedFileSlice

    digest = hashlib.sha256()
    encrypted = EncryptedFileSlice(source=source, key=key, nonce_hex=nonce_hex)
    try:
        with open(destination, "wb") as out:
            while True:
                chunk = encrypted.read(1024 * 1024)
                if not chunk:
                    break
                digest.update(chunk)
                out.write(chunk)
    finally:
        encrypted.close()
    return digest.hexdigest()


def format_content_disposition(filename: str, disposition_type: str = "inline") -> str:
    """
    Builds an RFC 6266 / RFC 5987 safe `Content-Disposition` header value.

    - The ASCII fallback parameter strips control characters (CR/LF/TAB/etc.)
      and double quotes so a raw filename can never break the header or inject
      additional headers (CWE-113).
    - The `filename*=UTF-8''...` parameter carries the full percent-encoded
      filename so non-ASCII names survive intact in modern browsers.
    """
    # Strip control characters and double quotes for the fallback ASCII parameter
    clean_ascii = re.sub(r'[\x00-\x1f\x7f"]', '', filename or "").encode('ascii', 'ignore').decode('ascii').strip() or "file"
    # RFC 5987 UTF-8 percent-encoded filename parameter
    encoded_utf8 = urllib.parse.quote(filename or "", safe='')
    return f'{disposition_type}; filename="{clean_ascii}"; filename*=UTF-8\'\'{encoded_utf8}'

